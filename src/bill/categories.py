# 认不出来的分类挂这个。它不解释什么，只表示「这笔有分类」。
UNKNOWN = "🏷️"


def emoji(category: str | None) -> str:
    """分类 -> 一个 emoji。空分类给空串。

    空分类是真实存在的一大类：微信账单根本没有分类列，换算下来整本全是空的。
    这里不替它们编一个通用图标；列表上另给一个问号，只表示「这个位置有东西、
    但这一笔没有分类」。
    """
    name = (category or "").strip().lower()
    if not name:
        return ""
    if name in _EXACT:
        return _EXACT[name]
    for keyword, mark in _KEYWORDS:
        if keyword in name:
            return mark
    return UNKNOWN
