# 认不出来的分类挂这个。它不解释什么，只表示「这笔有分类」。
UNKNOWN = "🏷️"


def emoji(category: str | None) -> str:
    """分类 -> 一个 emoji。空分类给空串（页面靠这个判断前面要不要留位置）。

    空分类是真实存在的一大类：微信账单根本没有分类列，换算下来整本全是空的。
    给它们统一挂个通用图标，等于每行都顶着同一个记号，白占地方。
    """
    name = (category or "").strip().lower()
    if not name:
        return ""
    if name in _EXACT:
        return _EXACT[name]
    for keyword, mark in _KEYWORDS:
        if keyword in name:
            return mark
    return UNKNOWN
