def canonical(category: str | None) -> str:
    """把分类名归一到统一体系。认不出的原样返回（空还是空）。

    不做关键词模糊匹配：那是 emoji 那一层的兜底。分类的**归类**必须精确，
    把「超市采购」猜成「日用百货」和把一笔钱算错没有区别；认不出就留着原文。
    """
    text = (category or "").strip()
    if not text:
        return ""
    return _ALIASES.get(text.lower(), text)


def _sql_literal(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def canonical_sql(column: str) -> str:
    """生成把一列分类名归一化的 SQL 表达式。

    映射只有上面这一份，Python（emoji、筛选候选）和 SQL（汇总分组、列表投影）
    都从它生成——两边各抄一份的话，迟早会有一处改歪，而改歪的结果是汇总页和
    列表页对同一笔给出两个分类，屏幕上什么都不说。
    """
    if not _ALIASES:
        return column
    clauses = " ".join(
        f"WHEN {_sql_literal(source)} THEN {_sql_literal(target)}"
        for source, target in sorted(_ALIASES.items())
    )
    return f"(CASE lower(trim({column})) {clauses} ELSE {column} END)"

