def _auto_pattern(keyword: str):
    """英文关键词的匹配式。中文返回 None，调用方按子串处理。

    四个字母以上只卡词首，这样 `restaurant` 能吃下 `restaurants`、
    `loan` 能吃下 `loans`；三个字母以下卡整词，免得 `bus` 命中 `business`。
    """
    if not keyword.isascii():
        return None
    escaped = re.escape(keyword)
    if len(keyword) >= 4:
        return re.compile(rf"(?<![a-z0-9]){escaped}")
    return re.compile(rf"(?<![a-z0-9]){escaped}(?![a-z0-9])")


_AUTO_PATTERNS = tuple(
    (keyword, category, _auto_pattern(keyword))
    for keyword, category in _AUTO_RULES
)


def detect(*texts: str | None) -> str:
    """根据对方 / 说明 / 备注猜一个分类。认不出返回空串。

    只给「未分类」的交易做**建议**，不直接写库。匹配不区分大小写，下划线当
    空格处理（`uber_eats` 和 `uber eats` 是同一个意思）。
    """
    haystack = " ".join(text for text in texts if text).casefold().replace("_", " ")
    if not haystack.strip():
        return ""
    for keyword, category, pattern in _AUTO_PATTERNS:
        if pattern is not None:
            if pattern.search(haystack):
                return category
        elif keyword in haystack:
            return category
    return ""


# 认不出来的分类挂这个。它不解释什么，只表示「这笔有分类」。
UNKNOWN = "🏷️"


def emoji(category: str | None) -> str:
    """分类 -> 一个 emoji。空分类给空串。

    空分类是真实存在的一大类：微信账单根本没有分类列，换算下来整本全是空的。
    这里不替它们编一个通用图标；列表上另给一个问号，只表示「这个位置有东西、
    但这一笔没有分类」。
    """
    name = (category or "").strip().lower()
    if not name:
        return ""
    if name in _EXACT:
        return _EXACT[name]
    for keyword, mark in _KEYWORDS:
        if keyword in name:
            return mark
    return UNKNOWN
